import { View } from 'react-native';
import type { FacultyReport } from '@/api/types';
import { shortDate } from '@/lib/format';
import { tr } from '@/lib/i18n';
import { colors, space, text } from '@/theme';
import { CriteriaBars, formatRating, TrendChart } from './Charts';
import { LogoMark } from './Logo';
import { Txt } from './Txt';
import { CommentCard, Panel } from './ui';

/**
 * One teacher's full results. Used by the teacher's own report, the admin's faculty report
 * and the clean print page (Print / Save as PDF).
 */
export function ReportView({ report, printable, schoolName }: { report: FacultyReport; printable?: boolean; schoolName?: string }) {
  const r = report;
  const s = r.student_ratings;
  const p = r.peer_ratings;

  return (
    <View style={{ gap: space.lg }}>
      {printable && (
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: space.sm, borderBottomWidth: 2, borderBottomColor: colors.navy, paddingBottom: space.md }}>
          <LogoMark size={44} />
          <View style={{ flex: 1 }}>
            <Txt weight="bold" size={text.h2}>{tr('Faculty Evaluation Report', 'Report ng Faculty Evaluation')}</Txt>
            {schoolName ? <Txt size={text.body} color={colors.muted}>{schoolName}</Txt> : null}
          </View>
        </View>
      )}

      <View style={{ flexDirection: 'row', flexWrap: 'wrap', gap: space.md }}>
        <Fact label={tr('Teacher', 'Guro')} value={r.teacher.name} />
        <Fact label={tr('Department', 'Departamento')} value={r.teacher.department ?? '—'} />
        <Fact label={tr('Period', 'Period')} value={r.period?.name ?? tr('All periods', 'Lahat ng period')} />
        <Fact label={tr('Generated', 'Ginawa')} value={shortDate(r.generated_at)} />
      </View>

      <View style={{ flexDirection: 'row', flexWrap: 'wrap', gap: space.md }}>
        <Big label={tr('Student rating', 'Rating ng estudyante')} value={formatRating(s.overall.average)} hint={tr(`${s.overall.responses} responses`, `${s.overall.responses} sagot`)} />
        {p.overall.responses > 0 && <Big label={tr('Peer rating', 'Peer rating')} value={formatRating(p.overall.average)} hint={tr(`${p.overall.responses} reviews`, `${p.overall.responses} review`)} />}
      </View>

      {r.trend.length >= 2 && (
        <Panel title={tr('Rating over time', 'Rating sa paglipas ng panahon')}>
          <TrendChart points={r.trend} />
        </Panel>
      )}

      {s.criteria.length > 0 && (
        <Panel title={tr('Student ratings by criteria', 'Rating ng estudyante ayon sa pamantayan')}>
          <CriteriaBars criteria={s.criteria} />
        </Panel>
      )}

      {p.criteria.length > 0 && (
        <Panel title={tr('Peer ratings by criteria', 'Peer rating ayon sa pamantayan')}>
          <CriteriaBars criteria={p.criteria} />
        </Panel>
      )}

      {r.classes.length > 0 && (
        <Panel title={tr('By class', 'Ayon sa klase')}>
          <View style={{ flexDirection: 'row', paddingBottom: space.xs, borderBottomWidth: 1, borderBottomColor: colors.border }}>
            <Txt weight="semibold" size={text.small} color={colors.muted} style={{ flex: 2 }}>{tr('Class', 'Klase')}</Txt>
            <Txt weight="semibold" size={text.small} color={colors.muted} style={{ flex: 1, textAlign: 'right' }}>{tr('Responses', 'Sagot')}</Txt>
            <Txt weight="semibold" size={text.small} color={colors.muted} style={{ flex: 1, textAlign: 'right' }}>{tr('Average', 'Average')}</Txt>
          </View>
          {r.classes.map((c, i) => (
            <View key={i} style={{ flexDirection: 'row', alignItems: 'center', paddingVertical: 6 }}>
              <Txt size={text.body} style={{ flex: 2 }} numberOfLines={2}>{[c.subject_code, c.subject_name, c.section].filter(Boolean).join(' · ')}</Txt>
              <Txt size={text.body} style={{ flex: 1, textAlign: 'right' }}>{String(c.responses)}</Txt>
              <Txt weight="semibold" size={text.body} style={{ flex: 1, textAlign: 'right' }}>{formatRating(c.average)}</Txt>
            </View>
          ))}
        </Panel>
      )}

      <Panel title={tr('Student comments', 'Mga komento ng estudyante')} subtitle={tr('Anonymous. Shown exactly as written.', 'Anonymous. Ipinapakita nang eksakto.')}>
        {r.comments.length === 0 ? (
          <Txt size={text.body} color={colors.muted}>{tr('No written comments.', 'Walang nakasulat na komento.')}</Txt>
        ) : (
          r.comments.map((c, i) => <CommentCard key={i} comment={c.comment} rating={c.rating} meta={[c.subject_code, c.submitted_at && shortDate(c.submitted_at)].filter(Boolean).join(' · ')} />)
        )}
      </Panel>

      {printable && (
        <Txt size={text.caption} color={colors.muted} style={{ textAlign: 'center' }}>
          {tr('Generated by TeachWise. Student identities are never recorded in this report.', 'Ginawa ng TeachWise. Hindi kailanman itinatala ang pagkakakilanlan ng estudyante sa report na ito.')}
        </Txt>
      )}
    </View>
  );
}

function Fact({ label, value }: { label: string; value: string }) {
  return (
    <View style={{ flex: 1, minWidth: 150, gap: 2 }}>
      <Txt size={text.caption} color={colors.muted} style={{ textTransform: 'uppercase', letterSpacing: 0.6 }}>{label}</Txt>
      <Txt weight="semibold" size={text.bodyLg}>{value}</Txt>
    </View>
  );
}

function Big({ label, value, hint }: { label: string; value: string; hint: string }) {
  return (
    <View style={{ flex: 1, minWidth: 180, backgroundColor: colors.card, borderRadius: 22, padding: space.lg, gap: 2, borderWidth: 1, borderColor: colors.borderSoft }}>
      <Txt weight="medium" size={text.body} color={colors.textSoft}>{label}</Txt>
      <View style={{ flexDirection: 'row', alignItems: 'baseline', gap: 6 }}>
        <Txt weight="bold" size={text.display} style={{ letterSpacing: -0.5 }}>{value}</Txt>
        <Txt size={text.body} color={colors.muted}>/ 5</Txt>
      </View>
      <Txt size={text.small} color={colors.muted}>{hint}</Txt>
    </View>
  );
}

/** Short text summary for sharing from a phone. */
export function reportSummary(r: FacultyReport): string {
  const lines = [
    `${tr('TeachWise report', 'TeachWise report')}: ${r.teacher.name}`,
    `${tr('Period', 'Period')}: ${r.period?.name ?? tr('All periods', 'Lahat ng period')}`,
    `${tr('Student rating', 'Rating ng estudyante')}: ${formatRating(r.student_ratings.overall.average)} / 5 (${r.student_ratings.overall.responses})`,
    `${tr('Peer rating', 'Peer rating')}: ${formatRating(r.peer_ratings.overall.average)} / 5 (${r.peer_ratings.overall.responses})`,
    '',
    ...r.student_ratings.criteria.map((c) => `• ${c.category}: ${formatRating(c.average)}`),
  ];
  return lines.join('\n');
}
